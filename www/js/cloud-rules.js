/* Firestore 보안 규칙 (Firebase 콘솔 → Firestore → 규칙 탭에 붙여 넣습니다)
   __ADMIN_EMAILS__ 자리에 관장·사범님 이메일이 들어갑니다. 앱의 서버 설정 화면이 이메일을 채운 규칙을 만들어 줍니다. */
(function () {
  'use strict';
  var TEMPLATE = [
    "rules_version = '2';",
    "",
    "// 태권도 통합 관리 - Firestore 보안 규칙",
    "// 관리자: 아래 목록의 이메일로 로그인하고 이메일 인증을 마친 계정",
    "// 학부모: 도장이 보낸 초대 코드로 연결된 기기. 자기 아이 정보만 읽을 수 있음",
    "service cloud.firestore {",
    "  match /databases/{database}/documents {",
    "    function signedIn() { return request.auth != null; }",
    "    function isAdmin() {",
    "      return signedIn() && request.auth.token.get('email_verified', false) == true",
    "        && request.auth.token.get('email', '') in [__ADMIN_EMAILS__];",
    "    }",
    "    function parentPath() { return /databases/$(database)/documents/parents/$(request.auth.uid); }",
    "    function isParent() { return signedIn() && exists(parentPath()); }",
    "    function isParentOf(sid) { return isParent() && sid in get(parentPath()).data.studentIds; }",
    "    function oldConsent(k) {",
    "      return resource.data.get('consent', null) == null ? null : resource.data.consent.get(k, null);",
    "    }",
    "",
    "    // 도장 설정: public·fitstats(이름 없는 체력 통계)는 학부모도 읽음, admin(비밀번호 등)은 관리자만",
    "    match /config/{doc} {",
    "      allow read: if isAdmin() || (isParent() && doc in ['public', 'fitstats']);",
    "      allow write: if isAdmin();",
    "    }",
    "",
    "    match /students/{sid} {",
    "      allow read: if isAdmin() || isParentOf(sid);",
    "      allow write: if isAdmin();",
    "      // 보호자: 전자 동의서 제출, 선택 동의 철회(사진 지우기)만 가능",
    "      allow update: if isParentOf(sid)",
    "        && request.resource.data.diff(resource.data).affectedKeys().hasOnly(['consent', 'photo'])",
    "        && request.resource.data.get('photo', null) in [null, resource.data.get('photo', null)]",
    "        && request.resource.data.consent.required == true",
    "        && (request.resource.data.consent.by == 'app'",
    "            || request.resource.data.consent.by == oldConsent('by'))",
    "        && request.resource.data.consent.get('smsSentAt', null) == oldConsent('smsSentAt');",
    "    }",
    "",
    "    // 출석(원생별·월별 문서), 회비, 체력측정, 승급심사: 학부모는 자기 아이 것만 읽기",
    "    match /att/{id} {",
    "      allow read: if isAdmin() || isParentOf(resource.data.sid);",
    "      allow write: if isAdmin();",
    "    }",
    "    match /payments/{id} {",
    "      allow read: if isAdmin() || isParentOf(resource.data.studentId);",
    "      allow write: if isAdmin();",
    "    }",
    "    match /fitness/{id} {",
    "      allow read: if isAdmin() || isParentOf(resource.data.studentId);",
    "      allow write: if isAdmin();",
    "    }",
    "    match /exams/{id} {",
    "      allow read: if isAdmin() || isParentOf(resource.data.studentId);",
    "      allow write: if isAdmin();",
    "    }",
    "",
    "    // 행사 안내는 학부모 누구나 읽음",
    "    match /events/{id} {",
    "      allow read: if isAdmin() || isParent();",
    "      allow write: if isAdmin();",
    "    }",
    "",
    "    // 참가신청서: 보호자는 자기 아이 신청서를 내고, 접수 상태일 때 취소만 가능",
    "    match /applications/{id} {",
    "      allow read: if isAdmin() || isParentOf(resource.data.studentId);",
    "      allow create: if isAdmin() || (isParentOf(request.resource.data.studentId)",
    "        && request.resource.data.by == 'parent' && request.resource.data.status == '접수'",
    "        && request.resource.data.paymentId == null);",
    "      allow update: if isAdmin() || (isParentOf(resource.data.studentId)",
    "        && request.resource.data.diff(resource.data).affectedKeys().hasOnly(['status', 'seen'])",
    "        && request.resource.data.status == '취소');",
    "      allow delete: if isAdmin();",
    "    }",
    "",
    "    // 알림장: 전체·반별은 학부모가 읽고, 개별 알림장은 아이별 사본(nview)으로만 읽음",
    "    match /notices/{id} {",
    "      allow read: if isAdmin() || (isParent() && resource.data.target.type in ['all', 'class']);",
    "      allow write: if isAdmin();",
    "    }",
    "    match /nview/{id} {",
    "      allow read: if isAdmin() || isParentOf(resource.data.sid);",
    "      allow write: if isAdmin();",
    "    }",
    "    match /nreads/{id} {",
    "      allow read: if isAdmin() || isParentOf(resource.data.sid);",
    "      allow create, update: if isAdmin() || (isParentOf(request.resource.data.sid)",
    "        && id == request.resource.data.nid + '_' + request.resource.data.sid);",
    "      allow delete: if isAdmin();",
    "    }",
    "    match /nreplies/{id} {",
    "      allow read: if isAdmin() || isParentOf(resource.data.sid);",
    "      allow create: if isAdmin() || (isParentOf(request.resource.data.sid) && request.resource.data.seen == false);",
    "      allow update, delete: if isAdmin();",
    "    }",
    "",
    "    // 학부모 기기 연결: 초대 코드를 쓴 같은 요청 안에서만 만들 수 있음",
    "    match /parents/{uid} {",
    "      allow read: if isAdmin() || (signedIn() && request.auth.uid == uid);",
    "      allow update: if isAdmin();",
    "      allow delete: if isAdmin() || (signedIn() && request.auth.uid == uid);",
    "      allow create: if signedIn() && request.auth.uid == uid",
    "        && get(/databases/$(database)/documents/invites/$(request.resource.data.code)).data.usedBy == null",
    "        && getAfter(/databases/$(database)/documents/invites/$(request.resource.data.code)).data.usedBy == uid",
    "        && request.resource.data.studentIds == get(/databases/$(database)/documents/invites/$(request.resource.data.code)).data.studentIds;",
    "    }",
    "    // 초대 코드: 코드를 아는 사람만 한 장씩 읽을 수 있고(목록 보기 불가), 한 번 쓰면 끝",
    "    match /invites/{code} {",
    "      allow get: if isAdmin() || (signedIn() && resource.data.usedBy == null && resource.data.expiresAt > request.time.toMillis());",
    "      allow list: if isAdmin();",
    "      allow create, delete: if isAdmin();",
    "      allow update: if isAdmin() || (signedIn() && resource.data.usedBy == null",
    "        && resource.data.expiresAt > request.time.toMillis()",
    "        && request.resource.data.diff(resource.data).affectedKeys().hasOnly(['usedBy', 'usedAt'])",
    "        && request.resource.data.usedBy == request.auth.uid",
    "        && existsAfter(/databases/$(database)/documents/parents/$(request.auth.uid)));",
    "    }",
    "    // 앱 푸시 알림 주소(토큰): 자기 기기 것만 쓰고 읽음. 보내기는 서버 프로그램(functions)이 함",
    "    match /push/{uid} {",
    "      allow get, delete: if signedIn() && request.auth.uid == uid;",
    "      allow create, update: if signedIn() && request.auth.uid == uid",
    "        && request.resource.data.keys().hasOnly(['token', 'role', 'at'])",
    "        && request.resource.data.token is string && request.resource.data.token.size() < 4096",
    "        && (request.resource.data.role == 'parent' || (request.resource.data.role == 'admin' && isAdmin()));",
    "    }",
    "  }",
    "}",
    ""
  ].join('\n');

  function rulesFor(emails) {
    var list = (emails || []).map(function (e) { return String(e).trim().toLowerCase(); }).filter(Boolean);
    if (!list.length) list = ['admin@example.com'];
    return TEMPLATE.replace('__ADMIN_EMAILS__', list.map(function (e) { return "'" + e.replace(/'/g, '') + "'"; }).join(', '));
  }

  if (typeof module !== 'undefined' && module.exports) module.exports = { TEMPLATE: TEMPLATE, rulesFor: rulesFor };
  if (typeof window !== 'undefined') window.CloudRules = { TEMPLATE: TEMPLATE, rulesFor: rulesFor };
})();
